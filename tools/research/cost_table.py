# Writes docs/pxcost.js: what each effect type costs, for the web editor's "this may not fit" warning (docs/edsound.js). The figures are the host engine's
# time per second of audio on the bundled guitar loops (tools/research/level_audit.c, every live type at its default settings) scaled to the pedal by
# one factor (POLY OCT FUZZ, 44 % on the pedal), except for the types read on a pedal (MEASURED below). An ESTIMATE for the rest, good to a factor of two:
# tools/research/pedal_load.mjs reads the real figures from a connected pedal.
#   python3 tools/research/cost_table.py
import csv, io, os, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCALE_PCT_PER_MS = 44.0 / 3.2           # per cent of an audio block per host ms/s (POLY OCT FUZZ: 44 % on the pedal, BlackBox_973, 3.2 ms/s here)
# read on a BlackBox running 973 (editor PING, per block, a few seconds each, no guitar: the figures do not depend on the input): they replace the scaled host
# figures, which are good to a factor of two (a Newton solver costs less on the pedal's FPU than its host time says: RANGEMASTER 12 %, not 26)
MEASURED = {"BST:RANGEMASTER": 12, "BST:EP BOOST": 5, "BST:MAXIMIZER": 6, "BST:FIXED WAH": 1, "BST:FUZZ FACE": 35, "EQ:HUM FILTER": 2, "OCT:POLY SHIFTER": 26, "OCT:POLY OCTAVE HQ": 26,
            "SYN:POLY OCT FUZZ": 44, "SYN:CHOIR": 20, "SYN:ENSEMBLE": 20, "REV:HALL": 9, "DLY:DIGITAL": 3}
exe = os.path.join(ROOT, "build", "level_audit"); os.makedirs(os.path.dirname(exe), exist_ok=True)
subprocess.run(["cc", "-O2", "-w", "-Iengine", "tools/research/level_audit.c", "engine/px_dsp.c", "firmware/px_math.c", "-lm", "-o", exe], cwd=ROOT, check=True)
rows = list(csv.DictReader(io.StringIO(subprocess.run([exe], cwd=ROOT, check=True, capture_output=True, text=True).stdout)))
if len(rows) < 40: raise SystemExit("cost_table: the audit gave only %d rows" % len(rows))
out = """// SPDX-License-Identifier: GPL-3.0-only
// Generated by tools/research/cost_table.py (do not edit): the estimated cost of each effect type on the pedal, in per cent of an audio block's time.
// From the host engine's time per second of audio (level_audit.c), scaled by one pedal reading (POLY OCT FUZZ: 44 %), and the types read on a BlackBox (973) as they read. An estimate, good to a factor of two; the pedal's own readings are PING's per-block shares (docs/EDITOR-PROTOCOL.md) and tools/research/pedal_load.mjs.
export const COST = {
"""
for r in rows:
    k = "%s:%s" % (r["block"], r["name"])
    out += '  "%s": %.1f,\n' % (k, float(MEASURED[k]) if k in MEASURED else max(0.5, float(r["ms_per_s"]) * SCALE_PCT_PER_MS))
out += """};
// the estimate for a block's type (0 for one that is not listed: the gate, a retired type)
export const costPct = (blockLabel, typeName) => COST[`${blockLabel}:${typeName}`] || 0;
"""
open(os.path.join(ROOT, "docs", "pxcost.js"), "w").write(out)
print("docs/pxcost.js:", len(rows), "types; heaviest:", max(rows, key=lambda r: float(r["ms_per_s"]))["name"])
