# Calibrates engine/px_trim.h against the bundled guitar loops (tools/research/level_audit.c): every live type, its knobs at noon (the boosts'
# level controls at unity), ends up as loud as the same loop with the block off (mean over the five loops, BS.1770), so switching a block on
# or changing a type keeps the loudness. The synth types are matched to the guitar they follow.
#   python3 tools/research/level_trim.py [passes=3]
import csv, io, os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TRIM = os.path.join(ROOT, "engine", "px_trim.h")
ARR = {"CMP": "CMP_DB", "OCT": "PIT_DB", "SFX": "SFX_DB", "MOD": "MOD_DB", "DLY": "DLY_DB", "REV": "REV_DB", "SYN": "SYN_DB"}
CNT = {"CMP_DB": "PX_CMP_COUNT", "PIT_DB": "PX_PIT_COUNT", "SFX_DB": "PX_SFX_COUNT", "MOD_DB": "PX_MOD_COUNT", "DLY_DB": "PX_DLY_COUNT", "REV_DB": "PX_REV_COUNT", "SYN_DB": "PX_SYN_COUNT"}
N = {"CMP_DB": 4, "PIT_DB": 7, "SFX_DB": 14, "MOD_DB": 11, "DLY_DB": 8, "REV_DB": 8, "SYN_DB": 34}
TOMB = {"SFX_DB": [8, 9, 10, 11, 12]}   # APPLAUSE, and ENHANCE, RANGEMASTER, EP BOOST, MAXIMIZER (BST types since v75): tombstones, never trimmed
NOTE = {"SFX_DB": "   /* ids 8 (APPLAUSE) and 9..12 (ENHANCE, RANGEMASTER, EP BOOST, MAXIMIZER, now BST types) are tombstones: 0 */",
        "SYN_DB": "   /* indexed by the SYNTH type id: the tombstones 0 */",
        "PIT_DB": "   /* (v70: the retired POLY OCTAVE removed) */"}
HEAD = """/* level matching, generated by tools/research/level_trim.py (tools/research/level_audit.c): BS.1770 loudness of the five bundled guitar loops at the pedal's level (x0.15).
 * dB per type with its knobs at noon (the boosts' level controls at unity), so that switching the block on, or changing its type, keeps the loudness of the guitar:
 * the mean over the loops is the same as the loop with the block off. No amps or cabinets in the chain since v70: these are the whole chain's trims. */
"""
def read():
    s = open(TRIM).read(); d = {}
    for name in CNT:
        m = re.search(r"static const float %s\[[A-Z_]+\] = \{([^}]*)\}" % name, s)
        if not m: sys.exit("level_trim: %s not found in %s (the file is left alone)" % (name, TRIM))
        v = [float(x.replace("f", "")) for x in re.findall(r"-?\d+\.?\d*f", m.group(1))]
        if len(v) != N[name]: sys.exit("level_trim: %s has %d entries, the table here says %d (a type was added? update N)" % (name, len(v), N[name]))
        d[name] = v
    for t in TOMB["SFX_DB"]: d["SFX_DB"][t] = 0.0
    return d
def write(d):
    out = HEAD
    for name in CNT:
        out += "static const float %s[%s] = {%s};%s\n" % (name, CNT[name], ", ".join("%.2ff" % x for x in d[name]), NOTE.get(name, ""))
    open(TRIM, "w").write(out)
def measure():
    exe = os.path.join(ROOT, "build", "level_audit"); os.makedirs(os.path.dirname(exe), exist_ok=True)
    subprocess.run(["cc", "-O2", "-w", "-Iengine", "tools/research/level_audit.c", "engine/px_dsp.c", "firmware/px_math.c", "-lm", "-o", exe], cwd=ROOT, check=True)
    return list(csv.DictReader(io.StringIO(subprocess.run([exe], cwd=ROOT, check=True, capture_output=True, text=True).stdout)))
d = read(); passes = int(sys.argv[1]) if len(sys.argv) > 1 else 3
orig = open(TRIM).read()                       # the engine reads px_trim.h to measure, so it is rewritten each pass: put it back if anything fails
try:
    for p in range(passes):
        write(d); rows = measure(); worst = 0
        for r in rows:
            a = ARR.get(r["block"])
            if not a: continue
            t, m = int(r["type"]), float(r["mean_db"]); worst = max(worst, abs(m))
            d[a][t] = max(-24.0, min(24.0, d[a][t] - m))
        print("pass %d: the largest mean error %.2f dB" % (p + 1, worst))
    write(d); rows = measure()
    print("final: the largest mean error %.2f dB" % max(abs(float(r["mean_db"])) for r in rows if r["block"] in ARR))
except BaseException:
    open(TRIM, "w").write(orig); print("level_trim: failed, engine/px_trim.h restored", file=sys.stderr); raise
