#!/usr/bin/env python3
"""Generate engine/px_triode_table.h (currents in mA, resistances in kΩ)."""
from math import exp, log1p

# Dempwolf & Zölzer, DAFx 2011, equations 10–12 and Table 1 (RSD-1).
MU = 103.2
SUPPLY = 250
PLATE = 100
CATHODE = 1.5
STOPPER = 33
STEPS = 32


def softplus(x):
    return max(x, 0) + log1p(exp(-abs(x)))


def load_line(voltage, resistance, current):
    """Solve I = current(voltage - resistance * I)."""
    lo, hi = 0.0, current(voltage)
    for _ in range(40):
        mid = (lo + hi) / 2
        if current(voltage - resistance * mid) > mid:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def grid(volts):
    return load_line(volts, STOPPER, lambda v: 0.6177 * (softplus(9.901 * v) / 9.901) ** 1.314 + 0.00008025)


def cathode(volts):
    return load_line(volts, PLATE / MU, lambda v: 2.242 * (softplus(3.40 * v) / 3.40) ** 1.26)


def currents(in_volts, cathode_volts):
    grid_current = grid(in_volts - cathode_volts)
    effective = in_volts - STOPPER * grid_current - (1 + 1 / MU) * cathode_volts
    cathode_current = cathode(effective + (SUPPLY + PLATE * grid_current) / MU)
    return cathode_current, cathode_current - grid_current


def constant(name, value):
    print(f"#define {name} {value:.9e}f")


def table(name, lo, hi, model, steps=STEPS):
    constant(f"{name}_MIN", lo)
    values = [model(lo + i / steps) for i in range((hi - lo) * steps + 1)]
    print(f"static const float {name}[{len(values)}] = {{")
    for i in range(0, len(values), 6):
        print("    " + ", ".join(f"{v:.8e}f" for v in values[i:i + 6]) + ",")
    print("};")


print("/* SPDX-License-Identifier: GPL-3.0-or-later */")
print("/* Generated by python3 tools/gen_triode.py. */")
bias = CATHODE * load_line(0, CATHODE, lambda v: currents(0, -v)[0])
_, plate_idle = currents(0, bias)
slope = (currents(0.001, bias)[1] - currents(-0.001, bias)[1]) / 0.002
constant("PXT_BIAS", bias)
constant("PXT_PLATE_IDLE", plate_idle)
constant("PXT_PLATE_SCALE", 1 / slope)
constant("PXT_STOPPER", STOPPER)
constant("PXT_CATHODE_KOHM", CATHODE)
constant("PXT_SUPPLY", SUPPLY)
constant("PXT_PLATE_KOHM", PLATE)
constant("PXT_GRID_FACTOR", 1 + 1 / MU)
constant("PXT_SUPPLY_TERM", SUPPLY / MU)
constant("PXT_PLATE_FEEDBACK", PLATE / MU)
constant("PXT_TABLE_STEPS", STEPS)
grid_join, grid_end, grid_steps = 5, 64, 2
constant("PXT_GRID_TAIL_MAX", grid_end)
constant("PXT_GRID_TAIL_STEPS", grid_steps)
constant("PXT_GRID_TAIL_SLOPE", (grid(grid_end + 0.001) - grid(grid_end - 0.001)) / 0.002)
table("PXT_GRID", -2, grid_join, grid)
table("PXT_GRID_TAIL", grid_join, grid_end, grid, grid_steps)
table("PXT_CATHODE", -4, 8, cathode)
