#!/usr/bin/env python3
"""v48: writes engine/px_acoustic_bank.h, the TRUMPET and CELLO SECTION sample bank in the firmware, from the bank
tools/sim/acoustic_prep.py made (docs/REALISTIC-INSTRUMENT-PROTOTYPE.md).

  python3 tools/sim/acoustic_prep.py && python3 tools/mk_acoustic_bank.py [build/acoustic] [engine/px_acoustic_bank.h]
  v49 (the trumpet from Iowa, recorded attack + synthesised sustain; the cello section from VSCO):
  python3 -I tools/sim/iowa_prep.py && python3 -I tools/sim/iowa_hybrid.py && python3 tools/mk_acoustic_bank.py --v49

The recordings are Versilian Studios' VSCO 2 Community Edition (CC0 1.0). Each sample is stored as 8-bit mu-law
(G.711 curve, mu = 255): the trumpet at 22.05 kHz, the cello section at 11.025 kHz (its sustain has next to nothing
above 5 kHz). Loop points come from acoustic_prep.py (halved for the cello). Needs numpy and scipy.
"""
import json, os, sys
import numpy as np
from scipy.io import wavfile
from scipy.signal import resample_poly

if len(sys.argv) > 1 and sys.argv[1] == "--v49":           # trumpet build/iowa_hybrid + cello section build/acoustic
    hy = json.load(open("build/iowa_hybrid/bank.json")); vs = json.load(open("build/acoustic/bank.json"))
    src = "build/acoustic_v49"; os.makedirs(os.path.join(src, "samples"), exist_ok=True)
    import shutil
    for d, b in (("build/iowa_hybrid", hy), ("build/acoustic", vs)):
        for e in b["samples"]:
            if (d == "build/acoustic") == (e["instrument_id"] == 1):
                shutil.copy(os.path.join(d, "samples", e["name"] + ".wav"), os.path.join(src, "samples", e["name"] + ".wav"))
    bank = dict(repository=vs["repository"], commit=vs["commit"],
                credits=["trumpet: University of Iowa Electronic Music Studios, Musical Instrument Samples (B-flat trumpet, non-vibrato mf/ff, 2003), "
                         "free for any project without restrictions, attack recorded + sustain synthesised from it (tools/sim/iowa_hybrid.py)",
                         f"cello section: Versilian Studios, VSCO 2 Community Edition, CC0 1.0, {vs['repository']} at {vs['commit']}"],
                samples=[e for e in hy["samples"] if e["instrument_id"] == 0] + [e for e in vs["samples"] if e["instrument_id"] == 1])
    json.dump(bank, open(os.path.join(src, "bank.json"), "w"), indent=1)
    dst = sys.argv[2] if len(sys.argv) > 2 else "engine/px_acoustic_bank.h"
else:
    src = sys.argv[1] if len(sys.argv) > 1 else "build/acoustic"
    dst = sys.argv[2] if len(sys.argv) > 2 else "engine/px_acoustic_bank.h"
    bank = json.load(open(os.path.join(src, "bank.json")))
MU = 255.0


def mulaw(x):
    y = np.sign(x) * np.log1p(MU * np.minimum(np.abs(x), 1.0)) / np.log1p(MU)
    return np.clip(np.round((y + 1.0) * 127.5), 0, 255).astype(np.uint8)


def unmulaw(c):
    y = c / 127.5 - 1.0
    return np.sign(y) * ((1 + MU) ** np.abs(y) - 1) / MU


out = ["/* engine/px_acoustic_bank.h -- GENERATED by tools/mk_acoustic_bank.py, do not edit.",
       " * v48: the sample bank of the SYN types TRUMPET and CELLO SECTION (engine/px_acoustic.h).",
       " * Recordings: " + "; ".join(bank.get("credits", [f"Versilian Studios, VSCO 2 Community Edition, CC0 1.0, {bank['repository']} at {bank['commit']}"])) + ".",
       " * 8-bit mu-law (mu = 255); trumpet 22.05 kHz, cello section 11.025 kHz. Per sample: source file, measured f0. */",
       "#ifndef PX_ACOUSTIC_BANK_H", "#define PX_ACOUSTIC_BANK_H", "#include <stdint.h>", "",
       "typedef struct { uint8_t instr, dyn; uint16_t rate; float f0; uint32_t n, ls, le, att; const uint8_t *d; } pxa_smp;   /* att: the recording's attack end */",
       "#ifdef __PI32V2__   /* on the pedal: after the flash code (firmware/app.ld .pxbank), out of the call range's way */",
       "#define PXA_BANK_SECTION __attribute__((section(\".pxbank\")))", "#else", "#define PXA_BANK_SECTION", "#endif", ""]
table = []
total = 0
for i, s in enumerate(bank["samples"]):
    r, x = wavfile.read(os.path.join(src, "samples", s["name"] + ".wav"))
    x = x.astype(np.float64) / 32768.0
    ls, le, att = s["loop_start"], s["loop_end"], s["attack_end"]
    rate = r
    if s["instrument_id"] == 1:                              # the cello section at half rate
        x = resample_poly(x, 1, 2); ls //= 2; le //= 2; att //= 2; rate = r // 2
    x = x[:le]
    c = mulaw(x)
    snr = 10 * np.log10(np.sum(x ** 2) / (np.sum((x - unmulaw(c.astype(np.float64))) ** 2) + 1e-20))
    total += len(c)
    out.append(f"/* {s['source'].replace('https://theremin.music.uiowa.edu/sound%20files/MIS/', 'Iowa MIS ').split('/blob/')[-1].split('/', 1)[-1] if 'uiowa' not in s['source'] else s['source'].replace('https://theremin.music.uiowa.edu/sound%20files/MIS/', 'Iowa MIS ')}: {s['f0_hz']} Hz, {s['dynamic']}, "
               f"mu-law SNR {snr:.0f} dB */")
    out.append(f"static const uint8_t PXA_D{i}[{len(c)}] PXA_BANK_SECTION = {{")
    for k in range(0, len(c), 32):
        out.append("    " + ",".join(str(int(v)) for v in c[k:k + 32]) + ",")
    out.append("};")
    table.append(f"    {{{s['instrument_id']}, {0 if s['dynamic'] == 'soft' else 1}, {rate}, {s['f0_hz']:.3f}f, {len(c)}, {ls}, {le}, {min(att, ls)}, PXA_D{i}}},")
out.append("")
out.append(f"#define PXA_NBANK {len(table)}")
out.append("static const pxa_smp PXA_BANK[PXA_NBANK] = {")
out += table
out.append("};")
dec = unmulaw(np.arange(256, dtype=np.float64))
out.append("static const float PXA_MU[256] = {")
for k in range(0, 256, 8):
    out.append("    " + ", ".join(f"{v:.8f}f" for v in dec[k:k + 8]) + ",")
out.append("};")
out.append(f"/* {total} bytes of samples */")
out.append("#endif")
open(dst, "w").write("\n".join(out) + "\n")
print(f"{dst}: {len(table)} samples, {total} bytes")
