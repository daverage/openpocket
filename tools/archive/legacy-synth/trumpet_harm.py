#!/usr/bin/env python3
"""v49 host experiment: harmonic tables of the Iowa trumpet sustains (build/iowa/bank.json + samples/), and the bytes a
recorded-attack + synthesised-sustain voice would store. Writes build/iowa/px_trumpet_harm.h (for
tools/archive/legacy-synth/trumpet_compare.c). Not firmware.   python3 -I tools/archive/legacy-synth/trumpet_harm.py [build/iowa]"""
import json, os, sys
import numpy as np
from scipy.io import wavfile
d = sys.argv[1] if len(sys.argv) > 1 else "build/iowa"
bank = json.load(open(os.path.join(d, "bank.json")))
NH = int(os.environ.get("NH", "32"))
rows, att_bytes = [], 0
for s in bank["samples"]:
    r, x = wavfile.read(os.path.join(d, "samples", s["name"] + ".wav")); x = x / 32768.0
    seg = x[s["loop_start"]:s["loop_end"]]
    L = 1 << int(np.ceil(np.log2(len(seg)))) * 1
    S = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), 4 * L)); f = np.fft.rfftfreq(4 * L, 1 / r)
    amps = []
    for h in range(1, NH + 1):
        fh = h * s["f0_hz"]
        if fh > r / 2 - 200: amps.append(0.0); continue
        m = (f > fh * 0.97) & (f < fh * 1.03); amps.append(float(S[m].max()) if m.any() else 0.0)
    a = np.array(amps); a = a / (np.sqrt(np.sum(a ** 2)) + 1e-12)          # unit power
    db = np.clip(np.round(20 * np.log10(a + 1e-6) + 80), 0, 255).astype(int)  # 8-bit dB (0 .. -80 dB, 1 dB steps)
    splice = s["attack_end"] + int(0.02 * r)                                  # the recorded attack + a 20 ms crossfade
    att_bytes += splice
    cen = float(np.sum(np.arange(1, NH + 1) * a ** 2) / np.sum(a ** 2))
    rows.append((s, db, splice, cen))
    print(f"{s['name']:18s} {s['f0_hz']:7.2f} Hz  attack splice {1000 * splice / r:4.0f} ms  centroid h {cen:4.1f}  "
          f"harmonics dB: {' '.join(str(int(v) - 80) for v in db[:12])} ...")
tab = NH * len(rows)
print(f"bytes: harmonic tables {tab} (8-bit dB), recorded attacks {att_bytes} (8-bit mu-law, 22.05 kHz), total {tab + att_bytes};"
      f" the looped bank: {sum(s['frames'] for s in bank['samples'])}")
with open(os.path.join(d, "px_trumpet_harm.h"), "w") as o:
    o.write("/* GENERATED by tools/archive/legacy-synth/trumpet_harm.py: Iowa trumpet sustain harmonics, 8-bit dB (value - 80), and the\n * attack splice length in samples of the bank's recordings. */\n")
    o.write(f"#define PTH_N {len(rows)}\n#define PTH_NH {NH}\n")
    o.write("static const struct { int dyn; float f0; int splice; unsigned char db[PTH_NH]; } PTH[PTH_N] = {\n")
    for s, db, splice, cen in rows:
        o.write(f"  {{{0 if s['dynamic'] == 'soft' else 1}, {s['f0_hz']:.3f}f, {splice}, {{{','.join(str(int(v)) for v in db)}}}}},\n")
    o.write("};\n")
